/// A simple placeholder that can be used to search all the hardcoded integers
/// in the code (useful to identify numbers that need to be changed with the default App Theme value).
extension IntHardcoded on int {
  int get hardcoded => this;
}

/// A simple placeholder that can be used to search all the hardcoded double
/// in the code (useful to identify numbers that need to be changed with the default App Theme value).
extension DoubleHardcoded on double {
  double get hardcoded => this;
}
